import { z } from "zod";

const envSchema = z.object({
  NEXT_PUBLIC_APP_URL: z.string().url().optional(),
  NEXT_PUBLIC_SUPABASE_DATA_API_URL: z.string().url().optional(),
  NEXT_PUBLIC_SUPABASE_URL: z.string().url().optional(),
  NEXT_PUBLIC_SUPABASE_ANON_KEY: z.string().min(1).optional(),
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: z.string().min(1).optional(),
  SUPABASE_SERVICE_ROLE_KEY: z.string().min(1).optional(),
  GEMINI_API_KEY: z.string().min(1).optional(),
  GEMINI_MODEL: z.string().min(1).optional(),
  ELASTICSEARCH_URL: z.string().url().optional(),
  ELASTICSEARCH_API_KEY: z.string().min(1).optional(),
  ELASTIC_SEARCH_API_KEY: z.string().min(1).optional(),
  AI_PROVIDER: z.enum(["groq", "xai", "gemini"]).optional(),
  GROQ_API_KEY: z.string().min(1).optional(),
  GROQ_MODEL: z.string().min(1).optional(),
  GROQ_API_URL: z.string().url().optional(),
  XAI_API_KEY: z.string().min(1).optional(),
  XAI_MODEL: z.string().min(1).optional(),
  XAI_API_URL: z.string().url().optional(),
  AI_ENABLE_FALLBACK: z.string().optional(),
  RESEND_API_KEY: z.string().min(1).optional(),
  RESEND_EMAILS_API_KEY: z.string().min(1).optional(),
  RESEND_WEBHOOK_SECRET: z.string().min(1).optional(),
  // Semantic response cache
  RESPONSE_CACHE_ENABLED: z.string().optional(),
  RESPONSE_CACHE_SIMILARITY_THRESHOLD: z.string().optional(),
  RESPONSE_CACHE_TTL_DAYS: z.string().optional(),
});

export const env = envSchema.parse({
  NEXT_PUBLIC_APP_URL: process.env.NEXT_PUBLIC_APP_URL,
  NEXT_PUBLIC_SUPABASE_DATA_API_URL: process.env.NEXT_PUBLIC_SUPABASE_DATA_API_URL,
  NEXT_PUBLIC_SUPABASE_URL: process.env.NEXT_PUBLIC_SUPABASE_URL,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY,
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,
  SUPABASE_SERVICE_ROLE_KEY: process.env.SUPABASE_SERVICE_ROLE_KEY,
  GEMINI_API_KEY: process.env.GEMINI_API_KEY,
  GEMINI_MODEL: process.env.GEMINI_MODEL,
  ELASTICSEARCH_URL: process.env.ELASTICSEARCH_URL,
  ELASTICSEARCH_API_KEY: process.env.ELASTICSEARCH_API_KEY ?? process.env.ELASTIC_SEARCH_API_KEY,
  ELASTIC_SEARCH_API_KEY: process.env.ELASTIC_SEARCH_API_KEY,
  AI_PROVIDER: process.env.AI_PROVIDER as "groq" | "xai" | "gemini" | undefined,
  GROQ_API_KEY: process.env.GROQ_API_KEY,
  GROQ_MODEL: process.env.GROQ_MODEL,
  GROQ_API_URL: process.env.GROQ_API_URL,
  XAI_API_KEY: process.env.XAI_API_KEY,
  XAI_MODEL: process.env.XAI_MODEL,
  XAI_API_URL: process.env.XAI_API_URL,
  AI_ENABLE_FALLBACK: process.env.AI_ENABLE_FALLBACK,
  RESEND_API_KEY: process.env.RESEND_API_KEY ?? process.env.RESEND_EMAILS_API_KEY,
  RESEND_EMAILS_API_KEY: process.env.RESEND_EMAILS_API_KEY ?? process.env.RESEND_API_KEY,
  RESEND_WEBHOOK_SECRET: process.env.RESEND_WEBHOOK_SECRET,
  RESPONSE_CACHE_ENABLED: process.env.RESPONSE_CACHE_ENABLED,
  RESPONSE_CACHE_SIMILARITY_THRESHOLD: process.env.RESPONSE_CACHE_SIMILARITY_THRESHOLD,
  RESPONSE_CACHE_TTL_DAYS: process.env.RESPONSE_CACHE_TTL_DAYS,
});
